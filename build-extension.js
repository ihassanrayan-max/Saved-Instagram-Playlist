import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const publicDir = path.join(__dirname, 'public');
const distDir = path.join(__dirname, 'dist');

// Files to copy from public to dist
const filesToCopy = [
  'manifest.json',
  'icon16.png',
  'icon48.png',
  'icon128.png',
  'robots.txt',
  'background.js',
  'playlist-model.js',
  'library-view.js',
  'extension-context.js',
  'play-item.js',
  'player-session.js',
  'playlist-repository.js'
];

console.log('📦 Building Chrome Extension...\n');

// Ensure dist directory exists
if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

// Copy files
filesToCopy.forEach(file => {
  const src = path.join(publicDir, file);
  const dest = path.join(distDir, file);
  
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, dest);
    console.log(`✓ Copied ${file}`);
  } else {
    throw new Error(`Required extension file missing: ${file}`);
  }
});

// Check if content.css exists (it should be generated by vite build)
const contentCssPath = path.join(distDir, 'content.css');
if (!fs.existsSync(contentCssPath)) {
  throw new Error('Required content.css is missing. Run npm run build.');
} else {
  console.log('✓ content.css found');
}

const manifest = JSON.parse(fs.readFileSync(path.join(distDir, 'manifest.json'), 'utf8'));
const required = [manifest.action.default_popup, manifest.background.service_worker,
  ...Object.values(manifest.icons), ...manifest.content_scripts.flatMap(entry => [...entry.js, ...(entry.css || [])]),
  ...manifest.web_accessible_resources.flatMap(entry => entry.resources)];
for (const file of required) {
  if (!fs.existsSync(path.join(distDir, file))) throw new Error(`Manifest references missing file: ${file}`);
}
for (const [size, file] of Object.entries(manifest.icons)) {
  const data = fs.readFileSync(path.join(distDir, file));
  if (data.length < 24 || data.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || data.readUInt32BE(16) !== Number(size) || data.readUInt32BE(20) !== Number(size)) {
    throw new Error(`Icon must be a real ${size}x${size} PNG: ${file}`);
  }
}
console.log('\n✅ Extension build complete!');
console.log('📁 Extension files are in the dist/ folder');
console.log('\n📝 Next steps:');
console.log('  1. Open Chrome and go to chrome://extensions/');
console.log('  2. Enable "Developer mode" (top right)');
console.log('  3. Click "Load unpacked" and select the dist/ folder');
console.log('  4. Visit Instagram saved collections to test!\n');
